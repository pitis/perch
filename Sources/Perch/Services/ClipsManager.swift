import AppKit
import Observation
import PerchCore
import UniformTypeIdentifiers

struct Clip: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, file, screenshot, recording }

    var id = UUID()
    var kind: Kind
    var createdAt = Date()
    var text: String?
    var path: String?
    /// Perch saved this file itself, so it's Perch's to delete. Your own screenshots and files never are.
    var ownsFile = false
    var copiedAt: Date?

    // `isDirectory:` keeps this from checking the disk, which can block on a prompt for a protected folder.
    var url: URL? { path.map { URL(fileURLWithPath: $0, isDirectory: false) } }
    var title: String { url?.lastPathComponent ?? String((text ?? "").prefix(60)) }
}

/// Recent screenshots, screen recordings and copied items. Kept in its own file, outside the planner backup.
@Observable
final class ClipsManager {
    private(set) var clips: [Clip] = []

    @ObservationIgnored private let directory = Store.supportDirectory.appendingPathComponent("Clips", isDirectory: true)
    @ObservationIgnored private var indexFile: URL { Store.supportDirectory.appendingPathComponent("clips.json") }
    @ObservationIgnored private var workspace: Workspace?
    @ObservationIgnored private var pollTimer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var watcher: DispatchSourceFileSystemObject?
    @ObservationIgnored private var scanWork: DispatchWorkItem?
    @ObservationIgnored private var knownNames: Set<String> = []
    @ObservationIgnored private var watchedFolder: URL?
    @ObservationIgnored private var saveWork: DispatchWorkItem?

    private static let limit = 40
    private static let maxTextLength = 100_000
    private static let maxImageBytes = 25 * 1024 * 1024
    /// What password managers and similar apps use to say "don't keep this". See nspasteboard.org.
    private static let privateTypes = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "com.nspasteboard.ConcealedType",
    ].map { NSPasteboard.PasteboardType($0) }

    func start(workspace: Workspace) {
        self.workspace = workspace
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        load()
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.pollPasteboard() }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer
        updateScreenshotWatcher()
    }

    // MARK: Persistence

    private func load() {
        guard let raw = try? Data(contentsOf: indexFile), let saved = try? Store.decoder.decode([Clip].self, from: raw) else { return }
        clips = saved
        pruneMissing()
    }

    func save() {
        saveWork?.cancel()
        guard let raw = try? Store.encoder.encode(clips) else { return }
        try? raw.write(to: indexFile, options: .atomic)
    }

    private func saveSoon() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.save() }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    private func insert(_ clip: Clip) {
        clips.insert(clip, at: 0)
        while clips.count > Self.limit { discard(clips.removeLast()) }
        saveSoon()
    }

    private func discard(_ clip: Clip) {
        if clip.ownsFile, let url = clip.url { try? FileManager.default.removeItem(at: url) }
    }

    func remove(_ clip: Clip) {
        clips.removeAll { $0.id == clip.id }
        discard(clip)
        saveSoon()
    }

    func removeAll() {
        clips.forEach(discard)
        clips = []
        saveSoon()
    }

    /// Whether reading the clip's file could raise a macOS prompt, because it's in a protected folder Perch hasn't been
    /// granted. Such files are only read when you use the clip.
    func mayPrompt(_ clip: Clip) -> Bool {
        clip.path.map { ProtectedFolders.mayPrompt($0, granted: watchedFolder) } ?? false
    }

    /// Clears out clips whose files were deleted or moved since they were added, off the main thread. Files in a
    /// protected folder are skipped unless it holds the screenshot folder Perch watches, because checking them
    /// could raise a macOS prompt, so their clips stay even after the file is gone.
    func pruneMissing() {
        let paths = clips.compactMap(\.path).filter { !ProtectedFolders.mayPrompt($0, granted: watchedFolder) }
        DispatchQueue.global(qos: .utility).async { [weak self] in
            // Only a file that's really gone, not one Perch was refused access to.
            let missing = Set(paths.filter { Darwin.access($0, F_OK) != 0 && errno == ENOENT })
            guard !missing.isEmpty else { return }
            DispatchQueue.main.async {
                guard let self else { return }
                self.clips.removeAll { $0.path.map(missing.contains) ?? false }
                self.saveSoon()
            }
        }
    }

    // MARK: Copied items

    private func pollPasteboard() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard workspace?.data.settings.captureCopied == true else { return }
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.privateTypes.contains) else { return }

        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if !urls.isEmpty {
            for url in urls.reversed() where !clips.contains(where: { $0.path == url.path }) {
                insert(Clip(kind: .file, path: url.path))
            }
            return
        }
        if let image = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            addImage(image)
            return
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
           text.count <= Self.maxTextLength {
            if let same = clips.firstIndex(where: { $0.kind == .text && $0.text == text }) {
                clips.remove(at: same)
            }
            insert(Clip(kind: .text, text: text))
        }
    }

    private func addImage(_ data: Data) {
        guard data.count <= Self.maxImageBytes, let rep = NSBitmapImageRep(data: data),
              let png = rep.representation(using: .png, properties: [:]) else { return }
        let file = directory.appendingPathComponent(UUID().uuidString + ".png")
        do {
            try png.write(to: file, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
            insert(Clip(kind: .image, path: file.path, ownsFile: true))
        } catch {
            try? FileManager.default.removeItem(at: file)
        }
    }

    // MARK: Screenshots and recordings

    func updateScreenshotWatcher() {
        watcher?.cancel()
        watcher = nil
        watchedFolder = nil
        guard workspace?.data.settings.captureScreenshots == true else { return }

        // The first touch of the Desktop folder shows a macOS permission prompt and blocks until it's answered,
        // which would freeze the whole app if it happened on the main thread.
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let folder = Self.screenshotFolder
            let fd = Darwin.open(folder.path, O_EVTONLY)
            guard fd >= 0 else { return }
            let existing = Set((try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? [])
            DispatchQueue.main.async {
                guard let self, self.workspace?.data.settings.captureScreenshots == true else {
                    close(fd)
                    return
                }
                self.watcher?.cancel()
                self.watchedFolder = folder
                self.knownNames = existing
                let source = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd, eventMask: .write, queue: .main)
                source.setEventHandler { [weak self] in self?.scheduleScan() }
                source.setCancelHandler { close(fd) }
                source.resume()
                self.watcher = source
                self.pruneMissing()
            }
        }
    }

    private static var screenshotFolder: URL {
        if let custom = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location"), !custom.isEmpty {
            let expanded = URL(fileURLWithPath: (custom as NSString).expandingTildeInPath)
            var isDirectory: ObjCBool = false
            if FileManager.default.fileExists(atPath: expanded.path, isDirectory: &isDirectory), isDirectory.boolValue { return expanded }
        }
        return FileManager.default.urls(for: .desktopDirectory, in: .userDomainMask)[0]
    }

    private func names(in folder: URL) -> Set<String> {
        Set((try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? [])
    }

    private func scheduleScan() {
        scanWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.scan() }
        scanWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.4, execute: work)
    }

    private func scan() {
        guard let folder = watchedFolder else { return }
        let current = names(in: folder)
        let added = current.subtracting(knownNames)
        knownNames = current
        for name in added.sorted() where !name.hasPrefix(".") {
            let url = folder.appendingPathComponent(name)
            guard let kind = Self.captureKind(of: url), !clips.contains(where: { $0.path == url.path }) else { continue }
            insert(Clip(kind: kind, path: url.path))
        }
    }

    /// What macOS calls a new recording ("Bildschirmaufnahme", "Înregistrare ecran"), since recordings often lack the attribute.
    /// Read from the screenshot tool's own strings, in the language it picks from the user's list; English stays as a fallback.
    private static let recordingNames: [String] = {
        let url = URL(fileURLWithPath: "/System/Library/CoreServices/screencaptureui.app/Contents/Resources/Localizable.loctable")
        let table = NSDictionary(contentsOf: url) as? [String: Any] ?? [:]
        let languages = Bundle.preferredLocalizations(from: Array(table.keys), forPreferences: Locale.preferredLanguages)
        return ["Screen Recording"] + languages.compactMap { (table[$0] as? [String: Any])?["Screen Recording"] as? String }
    }()

    static func captureKind(of url: URL) -> Clip.Kind? {
        let ext = url.pathExtension.lowercased()
        // macOS marks screenshots with this attribute in every language, which beats matching file names.
        let marked = getxattr(url.path, "com.apple.metadata:kMDItemIsScreenCapture", nil, 0, 0, 0) > 0
        if ["mov", "mp4"].contains(ext) {
            return marked || recordingNames.contains(where: url.lastPathComponent.hasPrefix) ? .recording : nil
        }
        if ["png", "jpg", "jpeg", "heic", "tiff", "pdf"].contains(ext) {
            return marked ? .screenshot : nil
        }
        return nil
    }

    // MARK: Dropped files

    func addDropped(_ providers: [NSItemProvider]) {
        for provider in providers where provider.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier) {
            provider.loadItem(forTypeIdentifier: UTType.fileURL.identifier, options: nil) { [weak self] item, _ in
                let url = (item as? URL) ?? (item as? Data).flatMap { URL(dataRepresentation: $0, relativeTo: nil) }
                guard let url, url.isFileURL else { return }
                DispatchQueue.main.async {
                    guard let self, !self.clips.contains(where: { $0.path == url.path }) else { return }
                    self.insert(Clip(kind: .file, path: url.path))
                }
            }
        }
    }

    // MARK: Using a clip

    func copy(_ clip: Clip) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let text = clip.text {
            pasteboard.setString(text, forType: .string)
        } else if let url = clip.url {
            let item = NSPasteboardItem()
            item.setString(url.absoluteString, forType: .fileURL)
            if clip.kind == .image || clip.kind == .screenshot, let png = try? Data(contentsOf: url) {
                item.setData(png, forType: .png)
            }
            pasteboard.writeObjects([item])
        }
        // This copy came from Perch, so don't add it back as a new clip.
        lastChangeCount = pasteboard.changeCount
        if let i = clips.firstIndex(where: { $0.id == clip.id }) {
            clips[i].copiedAt = Date()
            saveSoon()
        }
    }

    func open(_ clip: Clip) {
        if let url = clip.url {
            // Off the main thread: opening may be the first touch of a protected folder, which can wait on a prompt.
            DispatchQueue.global(qos: .userInitiated).async { NSWorkspace.shared.open(url) }
        } else if let text = clip.text {
            // Plain text has no file to open, so it goes to the default text editor through a temporary one.
            let file = FileManager.default.temporaryDirectory.appendingPathComponent("Perch clip \(clip.id.uuidString.prefix(6)).txt")
            if (try? text.write(to: file, atomically: true, encoding: .utf8)) != nil { NSWorkspace.shared.open(file) }
        }
    }

    func addSampleText(_ text: String) {
        clips.insert(Clip(kind: .text, text: text), at: 0)
    }

    func dragProvider(for clip: Clip) -> NSItemProvider {
        if let url = clip.url, let provider = NSItemProvider(contentsOf: url) { return provider }
        return NSItemProvider(object: (clip.text ?? "") as NSString)
    }
}
